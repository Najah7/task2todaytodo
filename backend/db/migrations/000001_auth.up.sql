CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE users (
    -- Q: Why 26 characters?
    -- A: We use ULID (Universally Unique Lexicographically Sortable Identifier) for user IDs.
    id text PRIMARY KEY CHECK (id ~ '^[0-9ABCDEFGHJKMNPQRSTVWXYZ]{26}$'),
    first_name text NOT NULL,
    last_name text NOT NULL,
    email citext NOT NULL UNIQUE,
    password text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    timezone text NOT NULL DEFAULT 'Asia/Tokyo'
);

CREATE TABLE roles (
    role_id text PRIMARY KEY CHECK (role_id ~ '^[a-z][a-z0-9_]*$'),
    name text NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TYPE permission_action AS ENUM ('create', 'read', 'update', 'delete');
CREATE TYPE permission_effect AS ENUM ('allow', 'deny');

CREATE TABLE managed_resources (
    resource_id text PRIMARY KEY CHECK (resource_id ~ '^[a-z][a-z0-9_]*$'),
    name text NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE permissions (
    permission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id text NOT NULL REFERENCES managed_resources(resource_id) ON DELETE CASCADE,
    action permission_action NOT NULL,
    effect permission_effect NOT NULL,
    description text NOT NULL CHECK (btrim(description) <> ''),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (resource_id, action, effect)
);

CREATE TABLE role_permissions (
    role_id text NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    permission_id bigint NOT NULL REFERENCES permissions(permission_id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (role_id, permission_id)
);

