INSERT INTO permissions (resource_id, action, effect, description)
SELECT resource_id, action::permission_action, effect::permission_effect,
       format('%s %s access (%s)', name, action, effect)
FROM managed_resources
CROSS JOIN LATERAL unnest(ARRAY['create', 'read', 'update', 'delete']) AS actions(action)
CROSS JOIN LATERAL unnest(ARRAY['allow', 'deny']) AS effects(effect)
WHERE (resource_id, action::text) IN (
    ('project', 'read'), ('project', 'update'), ('project', 'delete'),
    ('task', 'read'), ('task', 'create'), ('task', 'update'), ('task', 'delete'),
    ('todo_item', 'read'), ('todo_item', 'create'), ('todo_item', 'update'), ('todo_item', 'delete'),
    ('task_schedule', 'read'), ('task_schedule', 'create'), ('task_schedule', 'update'), ('task_schedule', 'delete'),
    ('task_assignment', 'update'), ('occurrence', 'update'),
    ('project_member', 'read'), ('project_member', 'create'), ('project_member', 'update'), ('project_member', 'delete'),
    ('deleted_history', 'read')
);

